import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:echoes_mobile/services/echoes_net.dart';
import 'package:echoes_mobile/services/net_protocol.dart';
import 'package:echoes_mobile/services/net_relays.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_test/flutter_test.dart';

const _seed = 'AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8=';
const _onion = 'aoqqpp7tzyil4hlq3umoos6atft6jvrqtosq2xy53sdgiesvgg4bqead';
const _pubkey =
    '98f96d22cbd9945641a26b1966c8b6ba4e537b1f51f7813c96ae3dc3c0180a30';

void main() {
  test('PC identity file, signed desktop event, and public link agree', () async {
    final seed = NetIdentity.parseSeed('{"v": 1, "seed": "$_seed"}');
    expect(seed, Uint8List.fromList(List.generate(32, (i) => i)));
    expect(() => NetIdentity.parseSeed(_onion), throwsFormatException);
    final me = await NetIdentity.fromSeed(seed);
    expect(me.onion, _onion);
    expect(me.pubkey, _pubkey);

    // Fixture generated by the Windows client's net_core.py and net_nostr.py.
    final desktop = <String, dynamic>{
      'pubkey': _pubkey,
      'created_at': 1767225600,
      'kind': 1,
      'tags': [
        ['t', 'echoes'],
        [
          'echoes-onion',
          _onion,
          'QacASo2chGoxX1ETRMnj64MVH84sqbi9rm6yy9uFHsJtOIuAcGwOfGl+IogB8g6G87dfvCILmhNV4r/ivn4uAQ==',
        ],
      ],
      'content': 'Строка 🎧\nВторая строка',
      'id': 'daa0deb9f45c6ffd0002825141e6855429ab9866b614ed3d8b23ac47fa052fbc',
      'sig':
          'ffe5c851b3c1cef2072b8aa80cbc91a87d6e6e60b2d5d18c87e0dfb795f14f55460ccf3e03f7fb4ccc4a52e11eb03b312dd891b05264910f64dbf825e8d93304',
    };
    expect(netVerify(desktop), isTrue);
    expect(await netLinkedOnion(desktop), _onion);
    expect(netVerify({...desktop, 'content': 'other'}), isFalse);
    final mobile = await me.event(1, 'Привет 🎧', [
      ['t', 'echoes'],
    ], work: 8);
    expect(netVerify(mobile), isTrue);
    expect(netWork(mobile['id'] as String), greaterThanOrEqualTo(8));
    expect(await netLinkedOnion(mobile), _onion);
  });

  test(
    'relay delivers signed posts and playlists and acknowledges writes',
    () async {
      final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
      addTearDown(() => server.close(force: true));
      FlutterSecureStorage.setMockInitialValues({});
      final net = EchoesNet(
        relays: NetRelays(urls: ['ws://127.0.0.1:${server.port}']),
      );
      expect(await net.loadIdentity(), isNull);
      final me = await net.signIn(_seed);
      expect((await net.loadIdentity())?.onion, _onion);

      final track = {
        'title': 'Numb',
        'artist': 'Linkin Park',
        'duration': 185,
        'url': 'https://youtu.be/kXYiU_JCYtU',
      };
      final playlist = await me.event(
        30078,
        jsonEncode({
          'pls': [
            {
              'name': 'Mix',
              'tracks': [track],
            },
          ],
        }),
        [
          ['d', 'echoes-playlists'],
        ],
      );
      final metadata = await me.event(0, '{"name":"Desktop profile"}', []);
      final stored = <NetJson>[metadata, playlist];
      server.transform(WebSocketTransformer()).listen((socket) {
        socket.listen((raw) {
          final frame = jsonDecode(raw as String) as List;
          if (frame[0] == 'EVENT') {
            final event = netObject(frame[1]);
            final valid = netVerify(event);
            if (valid) stored.add(event);
            socket.add(jsonEncode(['OK', event['id'], valid, '']));
          } else if (frame[0] == 'REQ') {
            // Send some irrelevant events as well to exercise client-side filtering.
            for (final event in stored) {
              socket.add(jsonEncode(['EVENT', frame[1], event]));
            }
            socket.add(jsonEncode(['EOSE', frame[1]]));
          }
        });
      });
      await net.post(me, 'Пост с телефона', null);
      final notes = await net.feed();
      expect(notes.single.text, 'Пост с телефона');
      await net.like(me, notes.single);
      await net.reply(me, notes.single, 'Ответ');
      final thread = await net.thread(notes.single);
      expect(thread.replies.single.text, 'Ответ');
      expect(thread.likes, {_pubkey});
      final profile = await net.profile(me.pubkey, onion: me.onion);
      expect(profile?.name, 'Desktop profile');
      expect(profile?.playlists.single.tracks.single.id, 'kXYiU_JCYtU');
      await net.signOut();
      expect(await net.loadIdentity(), isNull);
    },
  );
}
