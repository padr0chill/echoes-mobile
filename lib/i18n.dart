import 'dart:ui' show PlatformDispatcher;

/// Язык интерфейса. Строки в коде — русские; для английского берутся из словаря [_en].
/// 'auto' — как в настройках iPhone (русский для ru/uk/be/kk, иначе английский).
String appLangSetting = 'auto';

bool get isEn {
  if (appLangSetting == 'en') return true;
  if (appLangSetting == 'ru') return false;
  return !const {'ru', 'uk', 'be', 'kk'}.contains(PlatformDispatcher.instance.locale.languageCode);
}

/// Перевод: tr('Скачано: {0} тр.', [n]). Нет перевода — остаётся русский текст.
String tr(String ru, [List<Object?> args = const []]) {
  var s = isEn ? (_en[ru] ?? ru) : ru;
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  // «1 tracks» → «1 track» (в русском «тр.» число не склоняет)
  if (isEn && args.isNotEmpty) s = s.replaceAllMapped(_one, (m) => '1 ${m[1]}');
  return s;
}

